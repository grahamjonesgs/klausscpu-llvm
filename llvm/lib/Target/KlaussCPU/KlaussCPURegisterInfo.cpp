//===-- KlaussCPURegisterInfo.cpp - KlaussCPU Register Information --------===//
//
// KlaussCPU LLVM backend — register info implementation.
//
// Calling convention:
//   arg 0–3    : R0–R3   (A–D)   caller-saved
//   return     : R12     (M)     caller-saved
//   callee-saved: R4–R7  (E–H) + R15 (P = frame pointer)
//   temporaries : R8–R11, R13–R14 (I–L, N–O)  caller-saved
//
// Reserved registers:
//   SP  — hardware stack pointer, never visible to register allocator
//   R15 — frame pointer, always active (we always emit a frame pointer)
//
//===----------------------------------------------------------------------===//

#include "KlaussCPURegisterInfo.h"
#include "KlaussCPUFrameLowering.h"
#include "KlaussCPUInstrInfo.h"
#include "KlaussCPUSubtarget.h"
#include "llvm/CodeGen/MachineFrameInfo.h"
#include "llvm/CodeGen/MachineFunction.h"
#include "llvm/CodeGen/MachineInstrBuilder.h"
#include "llvm/CodeGen/RegisterScavenging.h"
#include "llvm/Support/ErrorHandling.h"

#define GET_REGINFO_TARGET_DESC
#include "KlaussCPUGenRegisterInfo.inc"

using namespace llvm;

// Callee-saved registers: E–H (R4–R7).
// R15 (frame pointer) is always reserved; it is saved/restored explicitly
// in emitPrologue/emitEpilogue (PUSH R15 / POP R15) so it must NOT appear
// here — if it did, PEI would try to spill it via storeRegToStackSlot which
// is not yet implemented.
static const MCPhysReg CalleeSavedRegs[] = {
  KlaussCPU::R4, KlaussCPU::R5, KlaussCPU::R6, KlaussCPU::R7,
  0 // null terminator
};

KlaussCPURegisterInfo::KlaussCPURegisterInfo()
    : KlaussCPUGenRegisterInfo(/*RA=*/0) {}

const MCPhysReg *
KlaussCPURegisterInfo::getCalleeSavedRegs(const MachineFunction *) const {
  return CalleeSavedRegs;
}

const uint32_t *
KlaussCPURegisterInfo::getCallPreservedMask(const MachineFunction &MF,
                                             CallingConv::ID) const {
  // CSR_KlaussCPU_RegMask is generated by tablegen from the CSR_KlaussCPU
  // CalleeSavedRegs definition in KlaussCPUCallingConv.td.
  return CSR_KlaussCPU_RegMask;
}

BitVector
KlaussCPURegisterInfo::getReservedRegs(const MachineFunction &MF) const {
  BitVector Reserved(getNumRegs());
  Reserved.set(KlaussCPU::SP);   // hardware stack pointer
  Reserved.set(KlaussCPU::R15);  // frame pointer (always active)
  return Reserved;
}

bool KlaussCPURegisterInfo::eliminateFrameIndex(MachineBasicBlock::iterator II,
                                                 int SPAdj,
                                                 unsigned FIOperandNum,
                                                 RegScavenger *RS) const {
  assert(SPAdj == 0 && "Unexpected SPAdj");
  MachineInstr &MI = *II;
  MachineBasicBlock &MBB = *MI.getParent();
  MachineFunction &MF = *MI.getParent()->getParent();
  const MachineFrameInfo &MFI = MF.getFrameInfo();
  const TargetInstrInfo &TII = *MF.getSubtarget().getInstrInfo();
  DebugLoc DL = MI.getDebugLoc();

  int FrameIndex = MI.getOperand(FIOperandNum).getIndex();
  int64_t BaseOffset = MFI.getObjectOffset(FrameIndex);

  // Sub-word register-addressed instructions (MEMGET8/16, MEMSET8/16) and
  // their 32-bit counterparts (MEMGET32, MEMSET32) have no offset operand —
  // only a single register address.  We materialise R15 + offset into a
  // scratch register via the register scavenger, then replace the FrameIndex
  // with that register.
  unsigned Opc = MI.getOpcode();
  if (Opc == KlaussCPU::MEMGET8  || Opc == KlaussCPU::MEMGET16 ||
      Opc == KlaussCPU::MEMSET8  || Opc == KlaussCPU::MEMSET16 ||
      Opc == KlaussCPU::MEMGET32 || Opc == KlaussCPU::MEMSET32) {
    assert(RS && "Register scavenger required for sub-word frame slot access");
    Register Scratch = RS->scavengeRegisterBackwards(
        KlaussCPU::GPRRegClass, II, /*RestoreAfter=*/false, SPAdj);
    // SETR scratch, <offset>     ; scratch = sign_extend(offset, 32→64)
    BuildMI(MBB, II, DL, TII.get(KlaussCPU::SETR), Scratch)
        .addImm(BaseOffset);
    // ADDR scratch, R15, scratch ; scratch = R15 + offset (frame address)
    BuildMI(MBB, II, DL, TII.get(KlaussCPU::ADDR), Scratch)
        .addReg(KlaussCPU::R15)
        .addReg(Scratch);
    MI.getOperand(FIOperandNum).ChangeToRegister(Scratch, /*isDef=*/false);
    return true;
  }

  // Standard case: instruction has a (base, offset) pair at
  // [FIOperandNum, FIOperandNum+1].  Replace FI with R15 and fold in the
  // frame-slot offset.
  int64_t Offset = BaseOffset + MI.getOperand(FIOperandNum + 1).getImm();
  MI.getOperand(FIOperandNum).ChangeToRegister(KlaussCPU::R15, /*isDef=*/false);
  MI.getOperand(FIOperandNum + 1).ChangeToImmediate(Offset);
  return false;
}

Register
KlaussCPURegisterInfo::getFrameRegister(const MachineFunction &MF) const {
  return KlaussCPU::R15; // P
}
